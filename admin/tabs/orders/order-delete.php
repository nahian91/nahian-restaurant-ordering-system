if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Handle Secure Order Deletion with Capability & Nonce Verification.
 *
 * @param string $orders_table Full orders table name.
 */
function nrtok_handle_order_delete( $orders_table ) {
	if ( ! current_user_can( 'manage_options' ) ) {
		wp_die( esc_html__( 'You do not have sufficient permissions to perform this action.', 'nahian-restaurant-ordering-system' ) );
	}

	$order_id = isset( $_GET['delete_order'] ) ? absint( $_GET['delete_order'] ) : 0;
	if ( $order_id <= 0 ) {
		return;
	}

	// Verify CSRF nonce generated by wp_nonce_url() in order-list.php.
	check_admin_referer( 'nrtok_delete_order_' . $order_id );

	global $wpdb;
	$svg_check = '<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><polyline points="20 6 9 17 4 12"></polyline></svg>';

	// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
	if ( $wpdb->get_var( $wpdb->prepare( 'SHOW TABLES LIKE %s', $orders_table ) ) !== $orders_table ) {
		return;
	}

	// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
	$deleted = $wpdb->delete(
		$orders_table,
		array( 'id' => $order_id ),
		array( '%d' )
	);

	if ( false !== $deleted && $deleted > 0 ) {
		echo '<div class="nrtok-alert nrtok-ord-alert-flex">' . $svg_check . '<span>' . sprintf( // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
			/* translators: %d: order ID */
			esc_html__( 'Order #%d deleted permanently!', 'nahian-restaurant-ordering-system' ),
			absint( $order_id )
		) . '</span></div>';
	} else {
		echo '<div class="nrtok-alert" style="background:#fef2f2; border-color:#fecaca; color:#b91c1c;">' . esc_html__( 'Order could not be deleted or was already removed.', 'nahian-restaurant-ordering-system' ) . '</div>';
	}
}